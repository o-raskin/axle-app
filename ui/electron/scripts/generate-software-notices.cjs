// Preserve the licenses of third-party code bundled into the desktop application.
const { mkdirSync, readFileSync, readdirSync, writeFileSync } = require("node:fs");
const { dirname, join, resolve } = require("node:path");

const packages = [
  { name: "react", licenseFile: "LICENSE" },
  { name: "react-dom", licenseFile: "LICENSE" },
  { name: "scheduler", licenseFile: "LICENSE" },
  { name: "three", licenseFile: "LICENSE" },
  { name: "meshoptimizer", licenseFile: "LICENSE.md" }
];

function generateNotices(root) {
  const lock = JSON.parse(readFileSync(join(root, "package-lock.json"), "utf8"));
  const separator = "=".repeat(72);
  const sections = packages.map(({ name, licenseFile }) => {
    const packagePath = `node_modules/${name}`;
    const installed = JSON.parse(readFileSync(join(root, packagePath, "package.json"), "utf8"));
    const locked = lock.packages?.[packagePath];
    if (installed.name !== name || !installed.version || installed.version !== locked?.version) {
      throw new Error(`Installed ${name} does not match package-lock.json. Install the locked dependencies before generating notices.`);
    }
    if (installed.license !== "MIT" || locked.license !== "MIT") {
      throw new Error(`${name} no longer declares the expected MIT license. Review its notice requirements before building.`);
    }
    const source = `${packagePath}/${licenseFile}`;
    const license = readFileSync(join(root, source), "utf8");
    if (!license.trim()) throw new Error(`The license file for ${name} is empty: ${source}`);
    return `${separator}\n${name} ${installed.version}\nLicense: ${installed.license}\nSource: ${source}\n${separator}\n\n${license}${license.endsWith("\n") ? "" : "\n"}`;
  });

  const runtimeSections = [];
  const visited = new Set();
  function includeRuntimeDependency(name, from) {
    const manifest = require.resolve(`${name}/package.json`, { paths: [from] });
    if (visited.has(manifest)) return;
    visited.add(manifest);
    const directory = dirname(manifest);
    const installed = JSON.parse(readFileSync(manifest, "utf8"));
    const packagePath = directory.slice(root.length + 1).replaceAll("\\", "/");
    const locked = lock.packages?.[packagePath];
    if (installed.version !== locked?.version || installed.license !== locked?.license) {
      throw new Error(`Installed ${name} does not match its locked version/license.`);
    }
    const files = readdirSync(directory).filter((file) => /^licen[sc]e(?:[.-]|$)/i.test(file));
    let license;
    if (!files.length && name === "lazy-val" && installed.version === "1.0.5" && installed.license === "MIT") {
      // This package publishes only out/ and omits a license file. Preserve its
      // actual author/declaration and identify the standard terms explicitly.
      const standardTerms = readFileSync(join(root, "node_modules/electron-updater/LICENSE"), "utf8").split("Permission is hereby granted")[1];
      if (!standardTerms) throw new Error("Cannot find standard MIT terms");
      license = `Author declared in package.json: ${installed.author}\nThe published lazy-val package declares MIT and omits a separate license file.\nStandard MIT terms (not a recovered original copyright notice):\n\nPermission is hereby granted${standardTerms}`;
    } else {
      if (!files.length) throw new Error(`No original license file found for ${name}. Review before packaging.`);
      license = files.map((file) => readFileSync(join(directory, file), "utf8")).join("\n");
    }
    runtimeSections.push(`${separator}\n${name} ${installed.version}\nLicense: ${installed.license}\nSource: ${packagePath}\n${separator}\n\n${license}\n`);
    for (const dependency of Object.keys(installed.dependencies || {})) includeRuntimeDependency(dependency, directory);
  }
  includeRuntimeDependency("electron-updater", root);

  return [
    "THIRD-PARTY SOFTWARE NOTICES",
    "",
    "The Axle desktop application includes the following third-party software.",
    "Generated by scripts/generate-software-notices.cjs from the installed",
    "package versions and their original license files. License text is copied",
    "verbatim below.",
    "",
    ...sections,
    ...runtimeSections
  ].join("\n").replace(/\n+$/, "\n");
}

if (require.main === module) {
  const root = resolve(__dirname, "..");
  const notices = generateNotices(root);
  const output = join(root, "resources/THIRD-PARTY-SOFTWARE-NOTICES.txt");
  mkdirSync(dirname(output), { recursive: true });
  writeFileSync(output, notices, "utf8");
  process.stdout.write("Generated software notices for renderer and updater dependencies.\n");
}

module.exports = { generateNotices };
